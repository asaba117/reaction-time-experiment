create table if not exists public.reaction_trials (
  id bigint generated by default as identity not null,
  participant_number bigint not null,
  block_number smallint not null,
  trial_number smallint not null,
  elapsed_time_ms integer not null,
  error_count integer not null,
  created_at timestamp with time zone not null default now(),
  constraint reaction_trials_pkey primary key (id)
) TABLESPACE pg_default;

-- Enable Row Level Security (RLS)
alter table public.reaction_trials enable row level security;

-- Allow experiment participants to upload trial results
create policy "Allow anonymous inserts"
on public.reaction_trials
for insert
to anon, authenticated
with check (true);

-- Allow reading results (optional, useful for querying results)
create policy "Allow anonymous select"
on public.reaction_trials
for select
to anon, authenticated
using (true);