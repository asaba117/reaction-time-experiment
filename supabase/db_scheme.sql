-- Run in the Supabase SQL Editor before deploying the updated frontend.
-- Safe to rerun: this also upgrades the original reaction_trials table in place.
-- Existing trial values are retained; no results are deleted or deduplicated.

begin;

create table if not exists public.reaction_trials (
  id bigint generated by default as identity not null,
  participant_number bigint not null,
  block_number smallint not null,
  trial_number smallint not null,
  elapsed_time_ms integer not null,
  error_count integer not null,
  created_at timestamp with time zone not null default now(),
  constraint reaction_trials_pkey primary key (id)
);

alter table public.reaction_trials
  add column if not exists client_record_id text;

-- Historical uploads did not store their browser record IDs. Give those rows
-- database-only IDs without changing their measurements. Their original browser
-- IDs cannot be reconstructed, so old lost-response retries need manual review.
update public.reaction_trials
set client_record_id = 'legacy-db-row:' || id::text
where client_record_id is null;

alter table public.reaction_trials
  alter column client_record_id set not null;

-- The unique constraint is the final guard against simultaneous/repeated uploads.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.reaction_trials'::regclass
      and conname = 'reaction_trials_client_record_id_key'
  ) then
    alter table public.reaction_trials
      add constraint reaction_trials_client_record_id_key unique (client_record_id);
  end if;
end;
$$;

-- NOT VALID preserves any out-of-range historical results while enforcing these
-- checks for every new insert/update. After reviewing old data, an administrator
-- can use ALTER TABLE ... VALIDATE CONSTRAINT <name> for each check below.
do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.reaction_trials'::regclass and conname = 'reaction_trials_client_record_id_check') then
    alter table public.reaction_trials add constraint reaction_trials_client_record_id_check
      check (char_length(client_record_id) between 1 and 200 and char_length(btrim(client_record_id)) > 0) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.reaction_trials'::regclass and conname = 'reaction_trials_participant_number_check') then
    alter table public.reaction_trials add constraint reaction_trials_participant_number_check
      check (participant_number between 0 and 999999) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.reaction_trials'::regclass and conname = 'reaction_trials_block_number_check') then
    alter table public.reaction_trials add constraint reaction_trials_block_number_check
      check (block_number between 1 and 3) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.reaction_trials'::regclass and conname = 'reaction_trials_trial_number_check') then
    alter table public.reaction_trials add constraint reaction_trials_trial_number_check
      check (trial_number between 1 and 20) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.reaction_trials'::regclass and conname = 'reaction_trials_elapsed_time_ms_check') then
    alter table public.reaction_trials add constraint reaction_trials_elapsed_time_ms_check
      check (elapsed_time_ms >= 0) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.reaction_trials'::regclass and conname = 'reaction_trials_error_count_check') then
    alter table public.reaction_trials add constraint reaction_trials_error_count_check
      check (error_count >= 0) not valid;
  end if;
end;
$$;

alter table public.reaction_trials enable row level security;
drop policy if exists "Allow anonymous select" on public.reaction_trials;
drop policy if exists "Allow anonymous inserts" on public.reaction_trials;
create policy "Allow anonymous inserts"
on public.reaction_trials
for insert
to anon, authenticated
with check (true);

-- Remove Supabase's broad defaults and any old explicit column permissions.
-- Browser clients may insert only trial fields, never read/update/delete results
-- or supply the database-generated id/created_at columns.
revoke all privileges on table public.reaction_trials from public, anon, authenticated;
revoke all privileges (id, client_record_id, participant_number, block_number, trial_number, elapsed_time_ms, error_count, created_at)
  on table public.reaction_trials from public, anon, authenticated;
grant usage on schema public to anon, authenticated;
grant insert (client_record_id, participant_number, block_number, trial_number, elapsed_time_ms, error_count)
  on public.reaction_trials to anon, authenticated;

do $$
declare
  identity_sequence text := pg_get_serial_sequence('public.reaction_trials', 'id');
begin
  if identity_sequence is not null then
    execute format('revoke all privileges on sequence %s from public, anon, authenticated', identity_sequence);
    execute format('grant usage on sequence %s to anon, authenticated', identity_sequence);
  end if;
end;
$$;

-- An explicit ON CONFLICT(column) target requires SELECT permission and a SELECT
-- RLS policy. This fixed insert-only RPC uses untargeted DO NOTHING instead, so
-- retries succeed without granting any access to stored participant results.
-- SECURITY INVOKER preserves the caller's INSERT privileges and RLS checks.
create or replace function public.upload_reaction_trials(trials jsonb)
returns void
language sql
volatile
security invoker
set search_path = ''
as $$
  insert into public.reaction_trials (
    client_record_id, participant_number, block_number, trial_number,
    elapsed_time_ms, error_count
  )
  select
    incoming.client_record_id, incoming.participant_number,
    incoming.block_number, incoming.trial_number,
    incoming.elapsed_time_ms, incoming.error_count
  -- Treat SQL NULL as an invalid JSON value instead of silently uploading no rows.
  from pg_catalog.jsonb_to_recordset(coalesce(trials, 'null'::jsonb)) as incoming (
    client_record_id text,
    participant_number bigint,
    block_number smallint,
    trial_number smallint,
    elapsed_time_ms integer,
    error_count integer
  )
  on conflict do nothing;
$$;

revoke all privileges on function public.upload_reaction_trials(jsonb) from public, anon, authenticated;
grant execute on function public.upload_reaction_trials(jsonb) to anon, authenticated, service_role;

-- Make the new RPC visible to the REST API after this transaction commits.
notify pgrst, 'reload schema';

commit;
